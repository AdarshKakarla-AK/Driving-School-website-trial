const translations: Record<Locale, Record<string, string>> = { en, kn, hi };

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = React.createContext<I18nCtx>({
  locale: "en",
  setLocale: () => {},
  t: (k) => k,
});

function subscribeLocale(onChange: () => void): () => void {
  window.addEventListener("storage", onChange);
  return () => window.removeEventListener("storage", onChange);
}

function readLocaleSnapshot(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === "kn" || v === "hi" || v === "en" ? v : "en";
  } catch {
    return "en";
  }
}

function readLocaleServerSnapshot(): Locale {
  return "en";
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const locale = React.useSyncExternalStore(subscribeLocale, readLocaleSnapshot, readLocaleServerSnapshot);

  const setLocale = React.useCallback((l: Locale) => {
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
    window.dispatchEvent(new Event("storage"));
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const t = React.useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const str = translations[locale][key] ?? translations.en[key] ?? key;
      if (!vars) return str;
      return str.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
    },
    [locale]
  );

  const value = React.useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return React.useContext(I18nContext);
}
